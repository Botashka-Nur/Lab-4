#Built-in Math Functions
x = min(5, 10, 25)
y = max(5, 10, 25)

print(x)
print(y)


#The abs() function returns the absolute (positive) value of the specified number:
x = abs(-7.25)
print(x)

#The pow(x, y) function returns the value of x to the power of y (x^y):
x = pow(4, 3)
print(x)


#The Math Module
import math

x = math.ceil(1.4)
y = math.floor(1.4)

print(x) 
print(y)